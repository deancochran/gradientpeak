/**
 * Onboarding Schemas
 *
 * Zod validation schemas for the smart onboarding flow. Defines input validation
 * for each step of the onboarding process and the complete onboarding payload.
 *
 * Used by:
 * - tRPC procedures for type-safe API validation
 * - Mobile app for client-side form validation
 * - Type inference for TypeScript interfaces
 */

import { z } from "zod";
import { ianaTimezoneSchema } from "../athlete-intelligence/planning-context";
import { isValidDateOfBirth } from "../profile/date-of-birth";
import { canonicalActivityCategorySchema } from "./activity-category";

export const onboardingStatusValues = [
  "provider_selection",
  "processing",
  "review",
  "completed",
] as const;

/** Durable lifecycle state. Provider selection closes atomically when processing starts. */
export const onboardingStatusSchema = z.enum(onboardingStatusValues);

export type OnboardingStatus = z.infer<typeof onboardingStatusSchema>;

/**
 * Experience level for onboarding.
 * Determines which baseline profile to use and which UI flows to show.
 */
export const experienceLevelSchema = z.enum([
  "beginner",
  "intermediate",
  "advanced",
  "skip", // Minimal setup, configure later
]);

export type ExperienceLevel = z.infer<typeof experienceLevelSchema>;

/** Canonical activity category selected during onboarding. */
export const onboardingActivityCategorySchema = canonicalActivityCategorySchema;

export type OnboardingActivityCategory = z.infer<typeof onboardingActivityCategorySchema>;

/** Personalization metadata selected during onboarding. */
export const onboardingIntentSchema = z.enum([
  "train_event",
  "improve_fitness",
  "track_activities",
  "groups",
  "follow_people",
  "coach_group",
  "explore",
]);

export type OnboardingIntent = z.infer<typeof onboardingIntentSchema>;

/** Source/state selected for a baseline field during onboarding. */
export const onboardingBaselineFieldSourceSchema = z.enum([
  "manual",
  "estimated",
  "imported",
  "cleared",
]);

export type OnboardingBaselineFieldSource = z.infer<typeof onboardingBaselineFieldSourceSchema>;

/**
 * Provenance for baseline fields submitted with every current completion request.
 * A cleared field suppresses only writes generated by this completion request;
 * historical observations remain unchanged until a separate evidence-management action removes them.
 */
export const onboardingBaselineFieldSourcesSchema = z
  .object({
    dob: onboardingBaselineFieldSourceSchema.optional(),
    gender: onboardingBaselineFieldSourceSchema.optional(),
    weight_kg: onboardingBaselineFieldSourceSchema.optional(),
    max_hr: onboardingBaselineFieldSourceSchema.optional(),
    resting_hr: onboardingBaselineFieldSourceSchema.optional(),
  })
  .strict();

export type OnboardingBaselineFieldSources = z.infer<typeof onboardingBaselineFieldSourcesSchema>;

/** A bounded set of distinct onboarding personalization selections. */
export const onboardingIntentArraySchema = z
  .array(onboardingIntentSchema)
  .max(7, { message: "Select no more than 7 onboarding intents" })
  .refine((intents) => new Set(intents).size === intents.length, {
    message: "Onboarding intents must be unique",
  });

