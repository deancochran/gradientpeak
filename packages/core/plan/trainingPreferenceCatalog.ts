import { z } from "zod";
import { planningPreferencesSchema } from "./planningPreferences";

export const trainingPreferenceTabSchema = z.enum([
  "preferences",
  "availability",
  "schedule",
  "training-style",
  "recovery",
  "goal-strategy",
  "baseline-fitness",
]);

export const trainingPreferenceControlSchema = z.enum([
  "integer-stepper",
  "bounded-number",
  "percent-slider",
  "boolean",
  "date",
  "weekday-list",
  "availability-windows",
  "sport-overrides",
  "disabled-row",
]);

export const trainingPreferencePlanLocalSupportSchema = z.enum([
  "editable",
  "profile-only",
  "derived",
]);

export const trainingPreferenceFieldSchema = z
  .object({
    id: z.string().min(1),
    tab: trainingPreferenceTabSchema,
    label: z.string().min(1),
    shortLabel: z.string().min(1),
    control: trainingPreferenceControlSchema,
    unit: z.string().nullable(),
    min: z.number().optional(),
    max: z.number().optional(),
    step: z.number().optional(),
    requiredDefault: z.number().optional(),
    globalPath: z.string().nullable(),
    planLocalKey: z.string().nullable(),
    planLocalSupport: trainingPreferencePlanLocalSupportSchema,
    testIdStem: z.string().min(1),
  })
  .strict();

export type TrainingPreferenceTab = z.infer<typeof trainingPreferenceTabSchema>;
export type TrainingPreferenceControl = z.infer<typeof trainingPreferenceControlSchema>;
export type TrainingPreferencePlanLocalSupport = z.infer<
  typeof trainingPreferencePlanLocalSupportSchema
>;
export type TrainingPreferenceField = z.infer<typeof trainingPreferenceFieldSchema>;

const planningPreferenceShape = planningPreferencesSchema.shape;

function assertPlanningPreferenceKey(key: string | null) {
  if (key !== null && !(key in planningPreferenceShape)) {
    throw new Error(`Unknown plan-local training preference key: ${key}`);
  }

  return key;
}

function field(input: TrainingPreferenceField) {
  return trainingPreferenceFieldSchema.parse({
    ...input,
    planLocalKey: assertPlanningPreferenceKey(input.planLocalKey),
  });
}

