export const trainingPreferenceTabs = trainingPreferenceTabSchema.options;

export function getTrainingPreferenceCatalogForTab(tab: TrainingPreferenceTab) {
  return trainingPreferenceCatalog.filter((field) => field.tab === tab);
}

export function getTrainingPreferenceCatalogForPlanLocalKey(key: string) {
  return trainingPreferenceCatalog.find((field) => field.planLocalKey === key) ?? null;
}
